// Regenerates llms.txt from content.js:        node build.js
// Also refetches BibTeX for every DOI first:   node build.js bibtex
const fs = require("fs");
const path = require("path");
globalThis.window = globalThis;
require("./content.js");
require("./markdown.js");
const S = window.SITE;
const out = (f) => path.join(__dirname, f);

// Parse one BibTeX entry as returned by doi.org and re-emit it in a clean, multi-line form.
function cleanBibtex(raw, p) {
  const m = raw.match(/@(\w+)\s*\{\s*([^,]*),/);
  if (!m) throw new Error("unparsable BibTeX for " + p.doi);
  let type = m[1].toLowerCase();
  const fields = {};
  let i = m.index + m[0].length;
  while (i < raw.length) {
    const f = raw.slice(i).match(/^\s*([A-Za-z]+)\s*=\s*/);
    if (!f) break;
    i += f[0].length;
    let val;
    if (raw[i] === "{") {
      let depth = 0, j = i;
      for (; j < raw.length; j++) { if (raw[j] === "{") depth++; else if (raw[j] === "}" && --depth === 0) break; }
      val = raw.slice(i + 1, j); i = j + 1;
    } else {
      const j = raw.slice(i).search(/[,}]/); val = raw.slice(i, i + j).trim(); i += j;
    }
    fields[f[1].toLowerCase()] = val.replace(/\s+/g, " ").trim();
    i = raw.indexOf(",", i) === -1 ? raw.length : raw.indexOf(",", i) + 1;
  }
  if (type === "inproceedings" && fields.journal && !fields.booktitle) { fields.booktitle = fields.journal; delete fields.journal; }
  if (type === "inbook") type = "incollection";
  if (fields.pages) fields.pages = fields.pages.replace(/[–—]/g, "--");
  fields.doi = p.doi;
  fields.url = "https://doi.org/" + p.doi;
  const keep = ["title", "author", "booktitle", "journal", "volume", "number", "pages", "publisher", "series", "year", "month", "doi", "url"];
  const last = fields.author.split(",")[0].toLowerCase().normalize("NFD").replace(/[^a-z]/g, "");
  const word = p.title.toLowerCase().split(/\W+/).find((w) => w.length > 3 && !["with", "from", "this", "what"].includes(w)) || "paper";
  const key = `${last}${fields.year}${word}`;
  const body = keep.filter((k) => fields[k]).map((k) => `  ${k} = {${fields[k]}}`).join(",\n");
  return `@${type}{${key},\n${body}\n}`;
}

async function fetchBibtex() {
  const all = [...S.conference, ...S.journal, ...S.chapters, ...S.preprints];
  const map = {};
  for (const p of all) {
    const r = await fetch("https://doi.org/" + p.doi, { headers: { Accept: "application/x-bibtex" } });
    if (!r.ok) throw new Error(`doi.org ${r.status} for ${p.doi}`);
    map[p.doi] = cleanBibtex(await r.text(), p);
    console.log("bibtex", p.doi);
  }
  fs.writeFileSync(out("bibtex.js"),
    "// Generated by `node build.js bibtex` from doi.org. Do not edit by hand.\nwindow.BIBTEX = " + JSON.stringify(map, null, 2) + ";\n");
}

(async () => {
  if (process.argv.includes("bibtex")) await fetchBibtex();
  fs.writeFileSync(out("llms.txt"), window.siteToMarkdown(S));
  console.log("wrote llms.txt");
})();
